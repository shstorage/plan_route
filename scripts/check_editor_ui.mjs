  async function connectChild(title) {
    const target = await until(async () => (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).find(t=>t.title.startsWith(title)), `detached ${title} target`)
    const socket = new WebSocket(target.webSocketDebuggerUrl)
    childSockets.push(socket)
    await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('Detached debugger connection timed out')), 5000)
      socket.addEventListener('open', () => { clearTimeout(timer); resolve() })
      socket.addEventListener('error', () => { clearTimeout(timer); reject(new Error('Detached debugger connection failed')) })
    })
    let serial = 0
    const requests = new Map()
    socket.addEventListener('close', () => {
      for (const request of requests.values()) { clearTimeout(request.timer); request.reject(new Error('Child target closed')) }
      requests.clear()
    })
    socket.addEventListener('message', (event) => {
      const message = JSON.parse(event.data)
      if (message.id) {
        const request = requests.get(message.id)
        if (!request) return
        requests.delete(message.id); clearTimeout(request.timer)
        if (message.error) request.reject(new Error(message.error.message))
        else request.resolve(message.result)
      } else if (message.method === 'Runtime.exceptionThrown') errors.push(message.params.exceptionDetails.exception?.description ?? message.params.exceptionDetails.text)
    })
    const send = (method, params = {}) => new Promise((resolve, reject) => {
      const id = ++serial
      const timer = setTimeout(() => { requests.delete(id); reject(new Error(`Child timeout: ${method}`)) }, 15000)
      requests.set(id, { resolve, reject, timer }); socket.send(JSON.stringify({ id, method, params }))
    })
    const read = async (expression) => {
      const result = await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true })
      if (result.exceptionDetails) throw new Error(result.exceptionDetails.exception?.description ?? result.exceptionDetails.text)
      return result.result.value
    }
    await send('Page.enable'); await send('Runtime.enable')
    await send('Emulation.setDeviceMetricsOverride', { width: 960, height: 900, deviceScaleFactor: 1, mobile: false })
    return { id: target.id, send, read, click: async (label) => {
      assert.ok(await read(`(() => { const b=[...document.querySelectorAll('button')].find(b=>b.checkVisibility() && b.textContent.trim()===${JSON.stringify(label)}); if(!b || b.disabled)return false; b.focus(); b.click(); return true })()`), `child button: ${label}`)
      await new Promise(resolve=>setTimeout(resolve,120))
    } }
  }
